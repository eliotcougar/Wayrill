import type { Connection } from '@xyflow/react';
import { getDefinition, getOutputPorts, portLabel } from './catalog';
import { connectionProblem } from './structure';
import type { GraphState, RuleEdge, RuleNode } from './types';

export function connectionIsEditable(graph: GraphState, edge: RuleEdge): boolean {
  return (
    edge.reconnectable !== false &&
    graph.nodes.find((node) => node.id === edge.source)?.data.kind !== 'xray-dns-servers'
  );
}

export function connectionSources(graph: GraphState): RuleNode[] {
  return graph.nodes.filter(
    (node) =>
      node.data.kind !== 'xray-dns-servers' && getOutputPorts(node.data.kind, node.data).length > 0,
  );
}

/** An unspecified new connection starts at an unused output; explicit/edit choices remain intact. */
export function preferredConnectionOutput(
  graph: GraphState,
  node: RuleNode,
  edgeId?: string,
): string {
  const ports = getOutputPorts(node.data.kind, node.data);
  return (
    ports.find(
      (port) =>
        !graph.edges.some(
          (edge) => edge.id !== edgeId && edge.source === node.id && edge.sourceHandle === port,
        ),
    ) ??
    ports[0] ??
    ''
  );
}

export function endpointDetail(node: RuleNode, graph?: GraphState): string {
  const title = getDefinition(node.data.kind).title;
  const ambiguous = graph?.nodes.some(
    (other) =>
      other.id !== node.id &&
      other.data.label === node.data.label &&
      other.data.kind === node.data.kind &&
      other.data.settings.tag === node.data.settings.tag,
  );
  return [
    title !== node.data.label && title,
    node.data.settings.tag,
    ambiguous && `ID ${node.id.slice(-8)}`,
  ]
    .filter(Boolean)
    .join(' · ');
}

export function connectionDescription(graph: GraphState, edge: Connection | RuleEdge): string {
  const source = graph.nodes.find((node) => node.id === edge.source);
  const target = graph.nodes.find((node) => node.id === edge.target);
  return `${source?.data.label ?? 'Missing source'} / ${portLabel(edge.sourceHandle ?? '', source?.data)} → ${target?.data.label ?? 'Missing destination'} / Input`;
}

export function sameConnection(a: Connection | RuleEdge, b: Connection | RuleEdge): boolean {
  return (
    a.source === b.source &&
    a.target === b.target &&
    (a.sourceHandle ?? null) === (b.sourceHandle ?? null) &&
    (a.targetHandle ?? null) === (b.targetHandle ?? null)
  );
}

/** Used by the chooser and every connection mutation, including dragging. */
export function connectionEditProblem(
  graph: GraphState,
  connection: Connection,
  edgeId?: string,
): string | null {
  if (edgeId) {
    const old = graph.edges.find((edge) => edge.id === edgeId);
    if (!old)
      return 'This connection no longer exists. Close the editor and choose another connection.';
    if (!connectionIsEditable(graph, old))
      return 'This query path is generated by Xray DNS settings. Edit the DNS servers to change it.';
  }
  if (graph.nodes.find((node) => node.id === connection.source)?.data.kind === 'xray-dns-servers')
    return 'Native DNS query paths follow the global routing filter automatically.';
  return connectionProblem(
    edgeId ? { ...graph, edges: graph.edges.filter((edge) => edge.id !== edgeId) } : graph,
    connection,
  );
}

/** Invalid or unchanged drafts retain the exact graph; edits preserve the edge's identity and metadata. */
export function applyConnectionEdit(
  graph: GraphState,
  connection: Connection,
  id: string,
  edgeId?: string,
): GraphState {
  if (connectionEditProblem(graph, connection, edgeId)) return graph;
  const old = edgeId ? graph.edges.find((edge) => edge.id === edgeId)! : undefined;
  if (old && sameConnection(old, connection)) return graph;
  const updated = { ...old, ...connection, id: old?.id ?? id, selected: true };
  return {
    ...graph,
    nodes: graph.nodes.map((node) => (node.selected ? { ...node, selected: false } : node)),
    edges: old
      ? graph.edges.map((edge) =>
          edge.id === old.id ? updated : edge.selected ? { ...edge, selected: false } : edge,
        )
      : [
          ...graph.edges.map((edge) => (edge.selected ? { ...edge, selected: false } : edge)),
          updated,
        ],
  };
}
