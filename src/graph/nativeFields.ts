export function nativeKey(object: Record<string, unknown>, field: NativeField): string {
  // expectedIPs takes priority unless empty, in which case Xray uses expectIPs.
  const primary = Object.keys(object).find((k) => k.toLowerCase() === field.key.toLowerCase());
  if (
    primary &&
    (!field.aliases ||
      (jsonArray(object[primary]) ? object[primary].length > 0 : !!object[primary]))
  )
    return primary;
  return (
    Object.keys(object).find((k) =>
      field.aliases?.some((a) => a.toLowerCase() === k.toLowerCase()),
    ) ??
    primary ??
    field.key
  );
}
export function nativeFieldText(object: Record<string, unknown>, field: NativeField): string {
  const value = object[nativeKey(object, field)];
  if (value === undefined || value === null) return '';
  if (field.type === 'list')
    return jsonArray(value)
      ? value.join('\n')
      : typeof value === 'string'
        ? value.split(',').join('\n')
        : jsonText(value);
  return field.type === 'json' ? JSON.stringify(value, null, 2) : jsonText(value);
}
export function nativeFieldValue(field: NativeField, text: string): unknown {
  if (text === '') return undefined;
  if (field.type === 'boolean') {
    if (!['true', 'false'].includes(text)) throw new Error('Choose a boolean value.');
    return text === 'true';
  }
  if (field.type === 'integer') {
    if (
      !/^-?\d+$/.test(text) ||
      !Number.isSafeInteger(Number(text)) ||
      Number(text) < (field.min ?? 0) ||
      Number(text) > (field.max ?? Number.MAX_SAFE_INTEGER)
    )
      throw new Error(
        `Enter a whole number from ${field.min ?? 0} to ${field.max ?? Number.MAX_SAFE_INTEGER}.`,
      );
    return Number(text);
  }
  if (field.type === 'select') {
    if (text.length > 4096 || text.includes('\0')) throw new Error('Invalid native option.');
    return text;
  }
  if (field.type === 'json') {
    const value = parseXrayJson(text);
    if (field.jsonShape === 'array' && !jsonArray(value)) throw new Error('Enter a JSON array.');
    if ((field.jsonShape === 'object' || !field.context) && !jsonRecord(value))
      throw new Error('Enter a JSON object.');
    return value;
  }
  if (field.type === 'list') {
    const values = text
      .split(/\r?\n/)
      .map((s) => s.trim())
      .filter(Boolean);
    for (const value of values) {
      const p =
        field.key === 'domains'
          ? domainProblem(value)
          : ['expectedIPs', 'unexpectedIPs'].includes(field.key) &&
              value !== '*' &&
              ipProblem(value)
            ? 'Use an IP address, CIDR or native geoip/ext rule.'
            : null;
      if (p) throw new Error(p);
    }
    return values;
  }
  if (field.context === 'protocol') {
    if (text.length > 131072 || text.includes('\0'))
      throw new Error('This value is too long or contains NUL.');
    return text;
  }
  if (field.key === 'clientIp' && !isIpLiteral(text))
    throw new Error('Enter an IPv4 or IPv6 address.');
  if (field.key === 'address') {
    const problem = dnsAddressProblem(text);
    if (problem) throw new Error(problem);
  }
  if (field.key === 'listen') {
    const match = /^(?:\[([^\]]+)\]|([^:]+)):(\d+)$/.exec(text);
    if (
      !match ||
      !isIpLiteral(match[1] ?? match[2]) ||
      Number(match[3]) < 1 ||
      Number(match[3]) > 65535
    )
      throw new Error(
        'Use an IP:port or [IPv6]:port. The service requires a loopback address and port 1024–65535.',
      );
  }
  if (text.length > 131072 || /[\0]/.test(text))
    throw new Error('This value is too long or contains NUL.');
  return text;
}
export function editNativeField(
  object: Record<string, unknown>,
  field: NativeField,
  text: string,
): Record<string, unknown> {
  const result = cloneJson(object),
    key = nativeKey(object, field),
    value = nativeFieldValue(field, text);
  for (const name of Object.keys(result))
    if (
      name.toLowerCase() === field.key.toLowerCase() ||
      field.aliases?.some((a) => a.toLowerCase() === name.toLowerCase())
    )
      delete result[name];
  if (value !== undefined) result[key] = value;
  return result;
}

