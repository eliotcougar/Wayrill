//! Runtime hazards which Xray's parse/build-only check cannot detect.
use crate::{ambiguous_keys, native, ApiError, Result};
use serde_json::Value;
use std::collections::{HashMap, HashSet};

fn invalid(message: impl Into<String>) -> ApiError {
    ApiError::new("INVALID_CONFIG", message)
}
fn object(value: &Value, path: &str) -> Result<()> {
    if !value.is_object() || ambiguous_keys(value) {
        return Err(invalid(format!(
            "{path} must be an object with unambiguous field names."
        )));
    }
    Ok(())
}
fn has(parent: &Value, key: &str) -> bool {
    parent
        .as_object()
        .is_some_and(|o| o.keys().any(|k| k.eq_ignore_ascii_case(key)))
}
fn optional_object(parent: &Value, key: &str, path: &str) -> Result<()> {
    if has(parent, key) {
        object(native(parent, key), path)?;
    }
    Ok(())
}
fn objects<'a>(parent: &'a Value, key: &str, path: &str) -> Result<&'a [Value]> {
    let value = native(parent, key);
    if !has(parent, key) {
        return Ok(&[]);
    }
    let values = value
        .as_array()
        .ok_or_else(|| invalid(format!("{path} must be an array.")))?;
    for value in values {
        object(value, path)?;
    }
    Ok(values)
}
fn string<'a>(parent: &'a Value, key: &str, path: &str) -> Result<Option<&'a str>> {
    let value = native(parent, key);
    if !has(parent, key) {
        return Ok(None);
    }
    value
        .as_str()
        .map(Some)
        .ok_or_else(|| invalid(format!("{path} must be a string.")))
}
pub fn validate_udp_listener_environment(config: &Value) -> Result<()> {
    if has(config, "env") {
        let environment = native(config, "env")
            .as_object()
            .ok_or_else(|| invalid("env must be an object."))?;
        for (key, value) in environment {
            if ![
                "WAYRILL_UDP_LISTENER_RECEIVE_BYTES",
                "WAYRILL_UDP_LISTENER_SEND_BYTES",
            ]
            .contains(&key.as_str())
                || !value.as_str().is_some_and(|value| {
                    !value.is_empty()
                        && value.bytes().all(|b| b.is_ascii_digit())
                        && value.parse::<u32>().is_ok_and(|n| n <= 64 * 1024 * 1024)
                })
            {
                return Err(invalid("env accepts only Wayrill UDP listener receive/send buffers, as decimal byte strings from 0 to 67108864."));
            }
        }
    }
    Ok(())
}
pub(crate) fn validate(config: &Value) -> Result<()> {
    validate_udp_listener_environment(config)?;
    for input in native(config, "inbounds").as_array().into_iter().flatten() {
        if native(input, "tag")
            .as_str()
            .is_some_and(|tag| tag.starts_with("wr-tun-resolver-native-"))
        {
            return Err(invalid(
                "Inbound tag prefix wr-tun-resolver-native- is reserved for the service resolver.",
            ));
        }
    }

    for server in native(native(config, "dns"), "servers")
        .as_array()
        .into_iter()
        .flatten()
    {
        let address = server
            .as_str()
            .or_else(|| native(server, "address").as_str());
        if address.is_some_and(|a| a.to_ascii_lowercase().starts_with("wayrill-dns:")) {
            return Err(invalid("Private resolver endpoints are generated by the service, not saved configurations."));
        }
    }

    for key in [
        "log",
        "routing",
        "dns",
        "policy",
        "stats",
        "metrics",
        "observatory",
        "burstObservatory",
    ] {
        optional_object(config, key, key)?;
    }
    for section in ["inbounds", "outbounds"] {
        for endpoint in objects(config, section, section)? {
            for key in ["settings", "streamSettings", "sniffing", "mux", "allocate"] {
                optional_object(endpoint, key, &format!("{section}.{key}"))?;
            }
            optional_object(
                native(endpoint, "streamSettings"),
                "sockopt",
                "streamSettings.sockopt",
            )?;
        }
    }
    let routing = native(config, "routing");
    let rules = objects(routing, "rules", "routing.rules")?;
    let balancers = objects(routing, "balancers", "routing.balancers")?;
    let policy = native(config, "policy");
    optional_object(policy, "system", "policy.system")?;
    // Level keys are identifiers, not case-insensitive JSON field names.
    if has(policy, "levels") {
        let levels = native(policy, "levels");
        let levels = levels
            .as_object()
            .ok_or_else(|| invalid("policy.levels must be an object."))?;
        for value in levels.values() {
            object(value, "policy.levels entry")?;
        }
    }
    let dns = native(config, "dns");
    if has(dns, "servers") {
        let servers = native(dns, "servers");
        let servers = servers
            .as_array()
            .ok_or_else(|| invalid("dns.servers must be an array."))?;
        for server in servers {
            if !server.is_string() {
                object(server, "dns.servers entry")?;
            }
        }
    }
    let outputs = config["outbounds"]
        .as_array()
        .ok_or_else(|| invalid("Missing outbounds."))?;
    let mut tags = HashMap::new();
    for (index, output) in outputs.iter().enumerate() {
        if let Some(tag) = string(output, "tag", "outbound.tag")? {
            // Untagged default outbounds remain legal. They cannot be referenced.
            if !tag.is_empty() && tags.insert(tag, index).is_some() {
                return Err(invalid("Duplicate outbound tag."));
            }
        }
    }
    if let Some(tag) = string(native(config, "metrics"), "tag", "metrics.tag")? {
        if !tag.is_empty() && tags.contains_key(tag) {
            return Err(invalid("The metrics tag conflicts with an outbound tag."));
        }
    }
    let mut group_tags = HashSet::new();
    for group in balancers {
        let tag = string(group, "tag", "balancer.tag")?.unwrap_or("");
        if tag.is_empty() || !group_tags.insert(tag) {
            return Err(invalid("Balancers need unique nonempty tags."));
        }
    }
    // VLESS reverse clients register their outbound handler dynamically.
    let mut dynamic = HashSet::new();
    for input in config["inbounds"].as_array().into_iter().flatten() {
        if input["protocol"] == "vless" {
            for client in native(native(input, "settings"), "clients")
                .as_array()
                .into_iter()
                .flatten()
            {
                if let Some(tag) = native(native(client, "reverse"), "tag").as_str() {
                    dynamic.insert(tag);
                }
            }
        }
    }
    let metrics = native(native(config, "metrics"), "tag")
        .as_str()
        .filter(|s| !s.is_empty());
    let known = |tag: &str| tags.contains_key(tag) || dynamic.contains(tag) || metrics == Some(tag);
    for rule in rules {
        if let Some(tag) =
            string(rule, "outboundTag", "rule.outboundTag")?.filter(|s| !s.is_empty())
        {
            if !known(tag) {
                return Err(invalid("A routing rule refers to a missing outbound tag."));
            }
        } else if let Some(tag) =
            string(rule, "balancerTag", "rule.balancerTag")?.filter(|s| !s.is_empty())
        {
            if !group_tags.contains(tag) {
                return Err(invalid("A routing rule refers to a missing balancer tag."));
            }
        }
    }
    for group in balancers {
        if let Some(tag) =
            string(group, "fallbackTag", "balancer.fallbackTag")?.filter(|s| !s.is_empty())
        {
            if !known(tag) {
                return Err(invalid("A balancer refers to a missing fallback outbound."));
            }
        }
    }
    // At most one definite successor per outbound. Conditional redispatch is
    // deliberately excluded: a syntactic cycle can still route safely by domain.
    let (loop_targets, loop_default) = first_targets(rules, &tags);
    let mut next = vec![None; outputs.len()];
    for (index, output) in outputs.iter().enumerate() {
        if output["protocol"] == "loopback" {
            let tag = string(
                native(output, "settings"),
                "inboundTag",
                "loopback.inboundTag",
            )?
            .unwrap_or("");
            next[index] = loop_targets.get(tag).copied().unwrap_or(loop_default);
        } else if !["blackhole", "block"].contains(&output["protocol"].as_str().unwrap_or("")) {
            let sockopt = native(native(output, "streamSettings"), "sockopt");
            if let Some(tag) =
                string(sockopt, "dialerProxy", "sockopt.dialerProxy")?.filter(|s| !s.is_empty())
            {
                // Dynamic reverse handlers can be absent before their clients
                // connect; Xray is responsible for resolving those references.
                if !known(tag) {
                    return Err(invalid("dialerProxy refers to a missing outbound tag."));
                }
                next[index] = tags.get(tag).copied();
            }
        }
    }
    reject_cycles(&next)
}

// Index the first potential match once, rather than scanning every routing
// row for every Loopback outbound in a large subscription.
fn first_targets<'a>(
    rules: &'a [Value],
    tags: &HashMap<&str, usize>,
) -> (HashMap<&'a str, Option<usize>>, Option<usize>) {
    let mut first = HashMap::new();
    for rule in rules {
        let conditional = rule.as_object().is_none_or(|fields| {
            fields.iter().any(|(key, value)| {
                if [
                    "type",
                    "ruleTag",
                    "outboundTag",
                    "balancerTag",
                    "inboundTag",
                ]
                .iter()
                .any(|k| key.eq_ignore_ascii_case(k))
                {
                    return false;
                }
                if key.eq_ignore_ascii_case("network") {
                    let both = match value {
                        Value::String(s) => {
                            let n = s.split(',').map(str::trim).collect::<Vec<_>>();
                            n.contains(&"tcp") && n.contains(&"udp")
                        }
                        Value::Array(a) => {
                            a.iter().any(|v| v == "tcp") && a.iter().any(|v| v == "udp")
                        }
                        _ => false,
                    };
                    if both {
                        return false;
                    }
                }
                !value.is_null()
                    && value.as_str() != Some("")
                    && !value.as_array().is_some_and(Vec::is_empty)
            })
        });
        let target = if conditional {
            None
        } else {
            native(rule, "outboundTag")
                .as_str()
                .and_then(|tag| tags.get(tag).copied())
        };
        let input = native(rule, "inboundTag");
        let inputs = match input {
            Value::Null => Vec::new(),
            Value::Array(values) => values.iter().filter_map(Value::as_str).collect::<Vec<_>>(),
            Value::String(value) if value.is_empty() => Vec::new(),
            Value::String(value) => value.split(',').collect(),
            _ => return (first, None),
        };
        if inputs.is_empty() {
            return (first, target);
        }
        for tag in inputs {
            first.entry(tag).or_insert(target);
        }
    }
    (first, Some(0))
}
fn reject_cycles(next: &[Option<usize>]) -> Result<()> {
    let mut color = vec![0u8; next.len()];
    for start in 0..next.len() {
        let mut node = Some(start);
        while let Some(index) = node {
            match color[index] {
                1 => return Err(ApiError::new(
                    "ROUTING_LOOP",
                    "Outbound chaining or unconditional Loopback redispatch forms a routing loop.",
                )),
                2 => break,
                _ => {
                    color[index] = 1;
                    node = next[index];
                }
            }
        }
        let mut node = Some(start);
        while let Some(index) = node {
            if color[index] != 1 {
                break;
            }
            color[index] = 2;
            node = next[index];
        }
    }
    Ok(())
}

// Canonicalize only fields read by the service. Arbitrary dictionary keys
// (hosts, headers, policy level identifiers) retain their exact spelling.
fn keys(parent: &mut Value, names: &[&str]) -> Result<()> {
    let Some(fields) = parent.as_object_mut() else {
        return Ok(());
    };
    for &name in names {
        let spellings = fields
            .keys()
            .filter(|key| key.eq_ignore_ascii_case(name))
            .cloned()
            .collect::<Vec<_>>();
        if spellings.len() > 1 {
            return Err(invalid("Resolve competing configuration field spellings."));
        }
        if let Some(key) = spellings.first().filter(|key| key.as_str() != name) {
            if let Some(value) = fields.remove(key) {
                fields.insert(name.into(), value);
            }
        }
    }
    Ok(())
}
pub(crate) fn canonicalize(config: &mut Value) -> Result<()> {
    for section in ["inbounds", "outbounds"] {
        if let Some(endpoints) = config[section].as_array_mut() {
            for endpoint in endpoints {
                keys(
                    endpoint,
                    &[
                        "protocol",
                        "tag",
                        "listen",
                        "port",
                        "settings",
                        "streamSettings",
                        "sniffing",
                        "mux",
                        "allocate",
                    ],
                )?;
                if let Some(Value::String(protocol)) = endpoint.get_mut("protocol") {
                    protocol.make_ascii_lowercase();
                }
                if let Some(settings) = endpoint.get_mut("settings") {
                    keys(
                        settings,
                        &[
                            "udp",
                            "auth",
                            "accounts",
                            "users",
                            "ip",
                            "userLevel",
                            "inboundTag",
                        ],
                    )?;
                }
                if let Some(stream) = endpoint.get_mut("streamSettings") {
                    keys(
                        stream,
                        &[
                            "network",
                            "method",
                            "security",
                            "sockopt",
                            "rawSettings",
                            "tcpSettings",
                        ],
                    )?;
                    if let Some(sockopt) = stream.get_mut("sockopt") {
                        keys(sockopt, &["dialerProxy", "interface", "domainStrategy"])?;
                    }
                }
            }
        }
    }
    if let Some(routing) = config.get_mut("routing") {
        keys(routing, &["rules", "balancers", "domainStrategy"])?;
        if let Some(rules) = routing.get_mut("rules").and_then(Value::as_array_mut) {
            for rule in rules {
                keys(
                    rule,
                    &[
                        "type",
                        "ruleTag",
                        "inboundTag",
                        "outboundTag",
                        "balancerTag",
                    ],
                )?;
            }
        }
    }
    for (section, names) in [
        (
            "dns",
            &[
                "servers",
                "hosts",
                "tag",
                "disableFallback",
                "disableFallbackIfMatch",
            ][..],
        ),
        ("policy", &["system", "levels"][..]),
        ("log", &["loglevel", "dnsLog", "maskAddress"][..]),
    ] {
        if let Some(value) = config.get_mut(section) {
            keys(value, names)?;
        }
    }
    Ok(())
}

